/**
 * Retrieve directors from LocalStorage (with fallback to default)
 */
export function getStoredDirectors(): Director[] {
  try {
    const raw = localStorage.getItem('clg_custom_directors');
    if (raw) {
      return JSON.parse(raw);
    }
  } catch (e) {
    console.error('Error reading custom directors:', e);
  }
  return DEFAULT_DIRECTORS;
}

export function getStoredQuestions(): {
  section1: EvaluationItem[];
  section2: EvaluationItem[];
  section3: EvaluationItem[];
  section4: EvaluationItem[];
} {
  try {
    const raw = localStorage.getItem('clg_custom_questions');
    if (raw) {
      const parsed = JSON.parse(raw);
      return {
        section1: parsed.section1 || DEFAULT_SECTION_1_ITEMS,
        section2: parsed.section2 || DEFAULT_SECTION_2_ITEMS,
        section3: parsed.section3 || DEFAULT_SECTION_3_ITEMS,
        section4: parsed.section4 || DEFAULT_SECTION_4_ITEMS,
      };
    }
  } catch (e) {
    console.error('Error reading custom questions:', e);
  }
  return {
    section1: DEFAULT_SECTION_1_ITEMS,
    section2: DEFAULT_SECTION_2_ITEMS,
    section3: DEFAULT_SECTION_3_ITEMS,
    section4: DEFAULT_SECTION_4_ITEMS,
  };
}

export function getStoredDirectorPermissions(): Record<string, DirectorPermissions> {
  try {
    const raw = localStorage.getItem('clg_director_permissions');
    if (raw) {
      return { ...DEFAULT_DIRECTOR_PERMISSIONS, ...JSON.parse(raw) };
    }
  } catch (e) {
    console.error('Error reading director permissions:', e);
  }
  return DEFAULT_DIRECTOR_PERMISSIONS;
}
