export const DEFAULT_FISCAL_YEARS: string[] = ['2569', '2570', '2571'];
export const FISCAL_YEARS: string[] = ['2569', '2570', '2571'];

export function getStoredFiscalYears(): string[] {
  try {
    const raw = localStorage.getItem('clg_fiscal_years');
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch {}
  return DEFAULT_FISCAL_YEARS;
}

export function saveStoredFiscalYears(years: string[]) {
  try {
    localStorage.setItem('clg_fiscal_years', JSON.stringify(years));
  } catch {}
}

export function getEvaluationStorageKey(
  company: CompanyId,
  year: string,
  evaluatorKey: string,
  isSupervisorMode: boolean = false,
  supervisorDept: string = 'CU'
): string {
  if (isSupervisorMode) {
    return `clg_eval_${company}_${year}_${evaluatorKey}_supervisor_${supervisorDept}`;
  }
  return `clg_eval_${company}_${year}_${evaluatorKey}`;
}

export function getLegacyEvaluationStorageKey(
  company: CompanyId,
  year: string,
  evaluatorKey: string,
  isSupervisorMode: boolean = false,
  supervisorDept: string = 'CU'
): string {
  if (isSupervisorMode) {
    return `clg_eval_${year}_${company}_${evaluatorKey}_supervisor_${supervisorDept}`;
  }
  return `clg_eval_${year}_${company}_${evaluatorKey}`;
}

